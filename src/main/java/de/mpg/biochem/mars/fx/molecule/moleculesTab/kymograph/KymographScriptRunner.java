package de.mpg.biochem.mars.fx.molecule.moleculesTab.kymograph;

import java.io.StringReader;
import java.io.StringWriter;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.concurrent.ExecutionException;

import org.scijava.Context;
import org.scijava.module.ModuleException;
import org.scijava.module.ModuleService;
import org.scijava.plugin.Parameter;
import org.scijava.script.ScriptInfo;
import org.scijava.script.ScriptModule;
import org.scijava.script.ScriptService;

import de.mpg.biochem.mars.molecule.MoleculeArchive;

/**
 * Runs scripts generated by the {@link KymographScriptBuilder}. Unlike the
 * Comments widgets, nothing is written to the archive lock screen so figures
 * can be generated without locking the archive.
 */
public class KymographScriptRunner {

	@Parameter
	private ScriptService scriptService;

	@Parameter
	private ModuleService moduleService;

	@Parameter
	private Context context;

	public KymographScriptRunner(Context context) {
		context.inject(this);
	}

	public static class Result {

		private final String image;
		private final Map<Integer, double[]> displayRanges;
		private final String error;

		Result(String image, Map<Integer, double[]> displayRanges, String error) {
			this.image = image;
			this.displayRanges = displayRanges;
			this.error = error;
		}

		/**
		 * @return The html encoded image or null if the script failed.
		 */
		public String getImage() {
			return image;
		}

		/**
		 * @return The display range used for each channel, if reported.
		 */
		public Map<Integer, double[]> getDisplayRanges() {
			return displayRanges;
		}

		public String getError() {
			return error;
		}

		public boolean isSuccess() {
			return image != null && error == null;
		}
	}

	public Result run(MoleculeArchive<?, ?, ?, ?> archive, String script)
		throws InterruptedException
	{
		ScriptInfo scriptInfo = new ScriptInfo(context, "kymograph.groovy",
			new StringReader(script));
		scriptInfo.setLanguage(scriptService.getLanguageByName("Groovy"));

		ScriptModule module;
		try {
			module = scriptInfo.createModule();
			context.inject(module);
		}
		catch (ModuleException e) {
			return new Result(null, null, "Could not create the script: " + e
				.getMessage());
		}

		Map<String, Object> inputs = new HashMap<>();
		inputs.put("scijavaContext", context);
		inputs.put("archive", archive);
		module.setInputs(inputs);

		StringWriter output = new StringWriter();
		StringWriter errors = new StringWriter();
		module.setOutputWriter(output);
		module.setErrorWriter(errors);

		try {
			moduleService.run(module, false).get();
		}
		catch (ExecutionException e) {
			return new Result(null, null, errors.toString() + e.getMessage());
		}

		Object image = module.getOutput(KymographScriptBuilder.IMAGE_OUTPUT);
		if (image == null) {
			String message = errors.toString();
			if (message.isEmpty()) message =
				"No image was created. Check the Fiji console for details.";
			return new Result(null, null, message);
		}

		return new Result((String) image, parseDisplayRanges(module.getOutput(
			KymographScriptBuilder.DISPLAY_RANGES_OUTPUT)), null);
	}

	private static Map<Integer, double[]> parseDisplayRanges(Object output) {
		Map<Integer, double[]> ranges = new LinkedHashMap<>();
		if (output == null) return ranges;
		for (String entry : output.toString().split(";")) {
			String[] parts = entry.split(":");
			if (parts.length != 3) continue;
			try {
				ranges.put(Integer.parseInt(parts[0].trim()), new double[] { Double
					.parseDouble(parts[1]), Double.parseDouble(parts[2]) });
			}
			catch (NumberFormatException e) {
				// Skip entries that can't be read.
			}
		}
		return ranges;
	}
}
